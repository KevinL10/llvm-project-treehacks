#ifndef LLVM_LIB_TARGET_FITS_FITSSUBTARGET_H
#define LLVM_LIB_TARGET_FITS_FITSSUBTARGET_H

#include "FitsFrameLowering.h"
#include "FitsISelLowering.h"
#include "FitsInstrInfo.h"
#include "FitsRegisterInfo.h"
#include "FitsSelectionDAGInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"

#define GET_SUBTARGETINFO_HEADER
#include "FitsGenSubtargetInfo.inc"

namespace llvm {
class FitsSubtarget : public FitsGenSubtargetInfo {
protected:
  FitsSelectionDAGInfo TSInfo;
  FitsInstrInfo InstrInfo;
  FitsFrameLowering FrameLowering;
  FitsTargetLowering TLInfo;
  FitsRegisterInfo RegInfo;

public:
  FitsSubtarget(const Triple &TT, StringRef CPU, StringRef FS,
                const TargetMachine &TM)
      : FitsGenSubtargetInfo(TT, CPU, CPU, FS), InstrInfo(*this),
        FrameLowering(*this, Align(8)), TLInfo(TM, *this) {}

  const FitsRegisterInfo *getRegisterInfo() const override { return &RegInfo; }

  const FitsInstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const FitsFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const FitsTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const FitsSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  /// Auto generated by tablegen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);
};

} // end namespace llvm
#endif